export function GuideScreen() {
  const [query, setQuery] = useState('')
  const q = query.trim().toLowerCase()
  const glossary = q ? GLOSSARY.filter(([t, d]) => t.toLowerCase().includes(q) || d.toLowerCase().includes(q)) : GLOSSARY
  return (
    <div className="stack guide">
      <input className="search" type="search" placeholder="용어 검색" value={query} onChange={(e) => setQuery(e.target.value)} aria-label="용어 검색" />
      {/* 검색 중엔 흐름 설명은 숨기고 용어 사전만 거른다. */}
      {!q &&
        SECTIONS.map(([title, text]) => (
          <section key={title} className="group">
            <div className="group-title">{title}</div>
            <p className="guide-text">{text}</p>
          </section>
        ))}
      <section className="group">
        <div className="group-title">용어 사전</div>
        {glossary.length === 0 && <p className="guide-text muted">찾는 용어가 없어요</p>}
        {glossary.map(([term, def]) => (
          <div key={term} className="glossary-row">
            <strong>{term}</strong>
            <p>{def}</p>
          </div>
        ))}
      </section>
    </div>
  )
}
