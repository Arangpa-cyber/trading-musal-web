/** 1천만원 · 3천만원 · 1억원 · 300억원처럼. */
function koreanAmount(won: number): string {
  const eok = won / 100_000_000
  if (eok >= 1) return Number.isInteger(eok) ? `${eok}억원` : `${eok.toFixed(1)}억원`
  const cheonman = won / 10_000_000
  return Number.isInteger(cheonman) ? `${cheonman}천만원` : `${Math.trunc(won / 10_000)}만원`
}

/** 경지 승급 조건 표 — 실제 판정 기준에서 바로 만든다. */
export function tierRequirementsText(): string {
  const blocks: string[] = []
  for (let tier = 0; tier <= LAST_TIER; tier++) {
    const req = tierRequirements(tier)
    const lines = [`${tier + 1}. ${tierName(tier)}`]
    if (req.minTotalAssets !== null && req.minWinRate !== null && req.minWinLossRatio !== null) {
      lines.push(`   - 총자산: ${koreanAmount(req.minTotalAssets)} 이상`, `   - 타율: ${Math.round(req.minWinRate * 100)}% 이상`, `   - 손익비: ${req.minWinLossRatio.toFixed(1)} 이상`)
    } else {
      lines.push(`   - 완료 거래 ${WINDOW_SIZE}건에 도달하면 삼류로 평가 시작`)
    }
    blocks.push(lines.join('\n'))
  }
  return blocks.join('\n\n')
}

